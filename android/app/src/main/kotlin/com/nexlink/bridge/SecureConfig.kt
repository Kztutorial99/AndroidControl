package com.nexlink.bridge

import javax.crypto.Cipher
import javax.crypto.spec.SecretKeySpec
import javax.crypto.spec.IvParameterSpec

internal object SecureConfig {

    private fun s1() = byteArrayOf(0x28, 0x88, 0x29, 0x69, 0x9C, 0xF2, 0xEB, 0x1B)
    private fun s2() = byteArrayOf(0x49, 0x96, 0x26, 0x57, 0x2F, 0x07, 0x6A, 0xE3)
    private fun s3() = byteArrayOf(0xE5, 0x6C, 0x73, 0xF3, 0xA0, 0xCE, 0xBB, 0xED)
    private fun s4() = byteArrayOf(0xC4, 0x1C, 0x09, 0xCD, 0x98, 0x08, 0xB9, 0x2C)
    private fun m1() = byteArrayOf(0x92, 0x6F, 0x59, 0x95, 0xF7, 0x11, 0xFA, 0xEC)
    private fun m2() = byteArrayOf(0x0D, 0x78, 0xA5, 0x42, 0xF8, 0x5A, 0x6F, 0xDC)
    private fun m3() = byteArrayOf(0xDA, 0xFB, 0x2F, 0xB0, 0x82, 0x1D, 0xFB, 0xAB)
    private fun m4() = byteArrayOf(0xA1, 0x99, 0x88, 0x41, 0x28, 0xEC, 0x13, 0x3E)

    private fun key(): ByteArray {
        val s = listOf(s1(), s2(), s3(), s4())
        val m = listOf(m1(), m2(), m3(), m4())
        val k = ByteArray(32)
        for (i in 0 until 32) k[i] = (s[i / 8][i % 8] xor m[i / 8][i % 8])
        return k
    }

    private val iv = byteArrayOf(0x41, 0xB0, 0x09, 0xB0, 0x68, 0xBB, 0x97, 0x7A, 0x5C, 0xCC, 0xB4, 0xE7, 0x2E, 0xB3, 0xAA, 0xC9)
    private val ct = byteArrayOf(0x3F, 0x3C, 0xB7, 0x0E, 0xE8, 0x10, 0xE6, 0x59, 0xA6, 0xB4, 0xC4, 0x35, 0x0E, 0x20, 0x86, 0xBF, 0xFB, 0x15, 0x4B, 0x0F, 0x93, 0x7C, 0x67, 0x38, 0xE2, 0x2F, 0x77, 0x57, 0x87, 0xD3, 0xF2, 0xDA, 0x81, 0xDA, 0xE3, 0x0D, 0xB5, 0x9B, 0x8F, 0x52, 0xC6, 0x13, 0x17, 0x8F, 0x22, 0xD7, 0xD2, 0xC1, 0x47, 0xEE, 0xDA, 0x52, 0x69, 0x48)

    fun serverUrl(): String {
        val k = key()
        val c = Cipher.getInstance("AES/CTR/NoPadding")
        c.init(Cipher.DECRYPT_MODE, SecretKeySpec(k, "AES"), IvParameterSpec(iv))
        return String(c.doFinal(ct), Charsets.UTF_8)
    }
}
